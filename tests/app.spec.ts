test('API requires real authentication and leaves financial services disabled', async ({ request }) => {
  const health = await request.get('http://127.0.0.1:3001/api/health')
  expect(health.ok()).toBeTruthy()
  expect(await health.json()).toMatchObject({ paymentsEnabled: false, tradingMode: 'simulation', authenticationConfigured: false })
  const me = await request.get('http://127.0.0.1:3001/api/me')
  expect(me.status()).toBe(401)
  const forged = await request.get('http://127.0.0.1:3001/api/me', { headers: { Authorization: 'Bearer not-a-real-token' } })
  expect(forged.status()).toBe(503)
  expect((await request.post('http://127.0.0.1:3001/api/deposits', { data: { amount: 1000, status: 'paid', role: 'admin' } })).status()).toBe(404)
})
