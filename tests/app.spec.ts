test('invite links copy, offer a manual fallback and share LipaHub URLs', async ({ page }) => {
  await page.addInitScript(() => Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async (value: string) => { localStorage.setItem('lipahub-test-clipboard', value) } } }))
  await demo(page)
  const card = page.locator('.invite-link-card')
  const primary = card.getByRole('textbox', { name: 'Invite link URL', exact: true })
  const primaryUrl = await primary.inputValue()
  expect(new URL(primaryUrl).origin).toBe('http://127.0.0.1:5173')
  expect(new URL(primaryUrl).pathname).toBe('/register')
  expect(new URL(primaryUrl).searchParams.get('ref')).toBe(await page.evaluate(() => JSON.parse(sessionStorage.getItem('lipahub-demo')!).id))
  await card.getByRole('button', { name: 'Copy link', exact: true }).click()
  await expect(card.getByRole('status')).toHaveText('Link copied.')
  expect(await page.evaluate(() => localStorage.getItem('lipahub-test-clipboard'))).toBe(primaryUrl)
  await card.getByRole('button', { name: 'Alternative link', exact: true }).click()
  const alternative = card.getByRole('textbox', { name: 'Alternative link URL', exact: true })
  expect(new URL(await alternative.inputValue()).pathname).toBe('/')
  await expect(primary).toHaveCount(0)
  await expect(card.getByRole('button', { name: 'Copy link', exact: true })).toHaveCount(1)
  await card.getByRole('button', { name: 'Invite link', exact: true }).click()
  await expect(primary).toBeVisible()
  await expect(alternative).toHaveCount(0)
  await card.getByRole('button', { name: 'Alternative link', exact: true }).click()
  await expect(alternative).toBeVisible()
  await expect(primary).toHaveCount(0)
  await page.evaluate(() => Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async () => { throw new Error('Clipboard unavailable') } } }))
  await card.locator('.invite-link-section').nth(1).getByRole('button', { name: 'Copy link', exact: true }).click()
  await expect(card.getByRole('status')).toContainText('copy it manually')
  await expect(alternative).toBeFocused()
  expect(await alternative.evaluate((el: HTMLInputElement) => [el.selectionStart, el.selectionEnd])).toEqual([0, (await alternative.inputValue()).length])
  expect(new URL((await card.getByRole('link', { name: 'Share on Facebook' }).getAttribute('href'))!).searchParams.get('u')).toBe(primaryUrl)
  expect(new URL((await card.getByRole('link', { name: 'Share on WhatsApp' }).getAttribute('href'))!).searchParams.get('text')).toContain(primaryUrl)
  expect(new URL((await card.getByRole('link', { name: 'Share on Twitter' }).getAttribute('href'))!).searchParams.get('text')).toContain(primaryUrl)
  expect(decodeURIComponent((await card.getByRole('link', { name: 'Share by email' }).getAttribute('href'))!)).toContain(primaryUrl)
  await card.getByRole('button', { name: 'Alternative link', exact: true }).press('Enter')
  await expect(card.getByRole('textbox', { name: 'Alternative link URL', exact: true })).toHaveCount(0)
  await page.setViewportSize({ width: 320, height: 800 })
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
})

