async function capture(page: Page, path: string, fullPage = true) {
  path = path.replace('artifacts/screenshots/', `artifacts/screenshots/${process.env.LIPAHUB_SCREENSHOT_RUN}/`)
  await mkdir(dirname(path), { recursive: true })
  await page.evaluate(async () => {
    await document.fonts.ready
    await new Promise<void>(resolve => requestAnimationFrame(() => requestAnimationFrame(() => resolve())))
  })
  await page.screenshot({ path, fullPage, scale: 'css', animations: 'disabled' })
}
