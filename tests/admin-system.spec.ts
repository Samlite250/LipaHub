import { selectCountry } from './helpers/country'
import { expect, test, type Page } from '@playwright/test'

async function admin(page: Page, section: string) {
  await page.goto(`/admin/${section}`)
  await page.getByRole('button', { name: 'Open admin demo' }).click()
  await expect(page.locator('.admin-environment')).toContainText('Demo workspace')
}
async function adminLink(page: Page, name: string) {
  const toggle = page.getByRole('button', { name: 'Open admin navigation' })
  if (await toggle.isVisible()) await toggle.click()
  await page.getByRole('link', { name, exact: true }).click()
}
test('user CRUD persists, prevents duplicate emails and protects the current administrator', async ({ page }) => {
  await admin(page, 'users')
  await expect(page.locator('.admin-user-table tbody tr')).toHaveCount(1)
  const self = page.locator('.admin-user-table tbody tr').first()
  await expect(self.getByRole('button', { name: /Delete user/ })).toBeDisabled()
  await self.getByRole('button', { name: /Edit user/ }).click()
  await expect(page.getByLabel('Account role')).toBeDisabled()
  await expect(page.getByLabel('Account status')).toBeDisabled()
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await page.getByRole('button', { name: 'Add user' }).click()
  await page.getByLabel('Display name', { exact: true }).fill('Test Member')
  await page.getByLabel('Email address', { exact: true }).fill('member@example.invalid')
  await page.getByLabel('Phone number', { exact: true }).fill('+25779000000')
  await page.getByRole('dialog').getByLabel('Country').selectOption('Burundi')
  await page.getByRole('button', { name: 'Create user', exact: true }).click()
  const user = page.locator('.admin-user-table tbody tr').filter({ hasText: 'member@example.invalid' })
  await expect(user).toContainText('Test Member')
  await user.getByRole('button', { name: 'Edit user member@example.invalid' }).click()
  await page.getByLabel('Display name', { exact: true }).fill('Updated Member')
  await page.getByLabel('Account status').selectOption('suspended')
  await page.getByLabel('Account role').selectOption('admin')
  await page.getByRole('button', { name: 'Save user', exact: true }).click()
  await expect(user).toContainText('Updated Member')
  await expect(user).toContainText('suspended')
  await expect(user).toContainText('Administrator')
  await page.getByRole('button', { name: 'Add user' }).click()
  await page.getByLabel('Display name', { exact: true }).fill('Duplicate Member')
  await page.getByLabel('Email address', { exact: true }).fill('MEMBER@example.invalid')
  await page.getByRole('button', { name: 'Create user', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('already in use')
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await admin(page, 'users')
  await expect(user).toContainText('Updated Member')
  await user.getByRole('button', { name: 'Delete user member@example.invalid' }).click()
  await expect(page.getByRole('button', { name: 'Permanently delete' })).toBeDisabled()
  await page.getByLabel('Deletion confirmation').fill('wrong@example.invalid')
  await expect(page.getByRole('button', { name: 'Permanently delete' })).toBeDisabled()
  await page.getByLabel('Deletion confirmation').fill('member@example.invalid')
  await page.getByRole('button', { name: 'Permanently delete' }).click()
  await expect(user).toHaveCount(0)
  await adminLink(page, 'Audit log')
  for (const action of ['users.create', 'users.update', 'users.delete']) await expect(page.locator('.admin-audit-table')).toContainText(action)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy()
})

test('resource CRUD updates published member content while drafts remain hidden', async ({ page }) => {
  await admin(page, 'resources')
  await page.getByRole('button', { name: 'Add resource' }).click()
  await page.getByLabel('Title', { exact: true }).fill('Test learning resource')
  await page.getByLabel('Description', { exact: true }).fill('A test course published by the administrator.')
  await page.getByRole('dialog').getByLabel('Publication status').selectOption('published')
  await page.getByLabel('Link (optional)').fill('https://example.com/course')
  await page.getByRole('button', { name: 'Save record' }).click()
  await expect(page.locator('.admin-content-list')).toContainText('Test learning resource')
  await page.getByRole('link', { name: 'Back to dashboard', exact: true }).click()
  await page.goto('/dashboard/courses')
  await expect(page.getByRole('heading', { name: 'Test learning resource', exact: true })).toBeVisible()
  await expect(page.getByRole('link', { name: 'Open resource' })).toHaveAttribute('href', 'https://example.com/course')
  await admin(page, 'resources')
  await page.getByRole('button', { name: 'Edit Test learning resource', exact: true }).click()
  await page.getByLabel('Title', { exact: true }).fill('Private draft resource')
  await page.getByRole('dialog').getByLabel('Publication status').selectOption('draft')
  await page.getByRole('button', { name: 'Save record' }).click()
  await expect(page.locator('.admin-content-list')).toContainText('Private draft resource')
  await page.goto('/dashboard/courses')
  await expect(page.getByRole('heading', { name: 'No published courses yet' })).toBeVisible()
  await admin(page, 'resources')
  await page.getByRole('button', { name: 'Delete Private draft resource', exact: true }).click()
  await page.getByLabel('Deletion confirmation').fill('Private draft resource')
  await page.getByRole('button', { name: 'Permanently delete' }).click()
  await expect(page.getByRole('heading', { name: 'No resources found' })).toBeVisible()
})

test('announcements respect country audiences and system settings reach support and dashboard', async ({ page }) => {
  await admin(page, 'announcements')
  await page.getByRole('button', { name: 'Add announcement' }).click()
  await page.getByLabel('Title', { exact: true }).fill('Rwanda member notice')
  await page.getByLabel('Description', { exact: true }).fill('Test announcement for Rwanda members.')
  await page.getByLabel('Audience').selectOption('Rwanda')
  await page.getByRole('dialog').getByLabel('Publication status').selectOption('published')
  await page.getByRole('button', { name: 'Save record' }).click()
  await expect(page.locator('.admin-content-list')).toContainText('Rwanda member notice')
  await adminLink(page, 'Settings')
  await page.getByLabel('Site name').fill('LipaHub Test Workspace')
  await page.getByLabel('Support email').fill('support@example.invalid')
  await page.getByLabel('Support message').fill('Test support message from the system administrator.')
  await page.getByRole('button', { name: 'Save system settings' }).click()
  await expect(page.getByRole('status')).toHaveText('System settings saved successfully.')
  await page.getByRole('link', { name: 'Back to dashboard', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Rwanda member notice' })).toBeVisible()
  await expect(page.locator('.member-footer')).toContainText('LipaHub Test Workspace')
  await page.goto('/dashboard/support')
  await expect(page.locator('.member-support-card')).toContainText('Test support message')
  await expect(page.getByRole('link', { name: 'Email support' })).toHaveAttribute('href', 'mailto:support%40example.invalid')
  await page.goto('/dashboard/profile')
  await selectCountry(page, 'Kenya')
  await page.getByRole('button', { name: 'Save changes' }).click()
  await page.goto('/dashboard')
  await expect(page.locator('.robot-card')).toHaveCount(33)
  await expect(page.getByRole('heading', { name: 'Rwanda member notice' })).toHaveCount(0)
  await admin(page, 'announcements')
  await page.getByRole('button', { name: 'Edit Rwanda member notice' }).click()
  await page.getByLabel('Audience').selectOption('All countries')
  await page.getByRole('button', { name: 'Save record' }).click()
  await expect(page.locator('.form-success')).toHaveText('Announcement saved successfully.')
  await page.getByRole('link', { name: 'Back to dashboard', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Rwanda member notice' })).toBeVisible()
  await admin(page, 'settings')
  await page.getByLabel('Show published announcements').uncheck()
  await page.getByRole('button', { name: 'Save system settings' }).click()
  await expect(page.getByRole('status')).toHaveText('System settings saved successfully.')
  await page.getByRole('link', { name: 'Back to dashboard', exact: true }).click()
  await expect(page.locator('.robot-card')).toHaveCount(33)
  await expect(page.locator('.member-announcements')).toHaveCount(0)
  await admin(page, 'announcements')
  await page.getByRole('button', { name: 'Delete Rwanda member notice' }).click()
  await page.getByLabel('Deletion confirmation').fill('Rwanda member notice')
  await page.getByRole('button', { name: 'Permanently delete' }).click()
  await expect(page.getByRole('heading', { name: 'No announcements found' })).toBeVisible()
})
