async function admin(page: Page) {
  await page.goto('/admin/payments')
  await page.getByRole('button', { name: 'Open local workspace' }).click()
  await expect(page.getByRole('button', { name: 'Save payment instructions' })).toBeVisible()
}
async function configureBurundi(page: Page, both = false) {
  await admin(page)
  for (const name of both ? ['Lumicash', 'Code'] : ['Lumicash']) {
    const section = page.locator('.admin-method-editor').filter({ has: page.getByRole('heading', { name, exact: true }) })
    await section.getByLabel('Recipient phone / code / wallet address').fill(`DEMO-${name.toUpperCase()}-ONLY`)
    await section.getByLabel('Recipient name (if applicable)').fill('Preview recipient')
    await section.getByLabel(`Instructions for ${name}`).fill(`TEST INSTRUCTIONS for ${name}. Do not send money. Submit a test image after reading these steps.`)
    await section.getByLabel(`Publish ${name}`).check()
  }
  await page.getByRole('button', { name: 'Save payment instructions' }).click()
  await expect(page.getByRole('status')).toHaveText('Instructions saved in this browser.')
}
async function member(page: Page, country = 'Burundi') {
  await page.goto('/register')
  await selectCountry(page, country)
  await page.getByRole('button', { name: 'Open practice workspace' }).click()
  await expect(page.locator('.robot-card')).toHaveCount(33)
}
async function image(page: Page) {
  const data = await page.evaluate(() => {
    const canvas = document.createElement('canvas'); canvas.width = 320; canvas.height = 140
    const context = canvas.getContext('2d')!; context.fillStyle = '#fff'; context.fillRect(0, 0, 320, 140); context.fillStyle = '#17272e'; context.font = '20px sans-serif'; context.fillText('TEST IMAGE', 25, 50); context.font = '14px sans-serif'; context.fillText('Not a payment receipt', 25, 90)
    return canvas.toDataURL('image/png').split(',')[1]
  })
  return { name: 'test-image-not-a-receipt.png', mimeType: 'image/png', buffer: Buffer.from(data, 'base64') }
}
async function proofFields(page: Page) {
  await page.getByLabel('Full names').fill('Preview Member')
  await page.getByLabel('Phone number', { exact: true }).fill('+25779000000')
  await page.locator('input[type=file]').setInputFiles(await image(page))
  await page.getByRole('checkbox').check()
  await expect(page.getByRole('button', { name: 'Submit payment proof' })).toBeEnabled()
}
