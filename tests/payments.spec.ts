test('private proof and admin API routes reject unauthenticated and forged-role requests', async ({ request }) => {
  const api = 'http://127.0.0.1:3001/api/robot-payments'
  for (const path of ['/requests', '/instructions/Burundi', '/admin/requests', '/requests/not-mine/files/not-mine']) expect((await request.get(api + path)).status()).toBe(401)
  expect((await request.put(api + '/admin/instructions/Burundi', { data: { role: 'admin', methods: [] } })).status()).toBe(401)
  expect((await request.post(api + '/requests', { data: { userId: 'other-user', status: 'verified', bonus: 8000000 } })).status()).toBe(401)
  expect((await request.patch(api + '/admin/requests/anything', { data: { role: 'admin', status: 'verified' } })).status()).toBe(401)
})
